"""Продление катящегося барабана следующей месячной программой — чистое ядро.

Требование владельца (вариант А, один катящийся график): «Одна программа —
один месяц. План фиксируется и после этого не меняется». Барабан ОДИН и
катится — вместо второго графика на следующий месяц августовские плитки
ДОБАВЛЯЮТСЯ в существующий активный график, не трогая уже релизнутые,
закрытые выпуском и перенесённые вправо июльские плитки.

Здесь — только чистые решения без Frappe (дедуп по программе и расширение
горизонта), чтобы покрыть их pytest'ом. Раскладка объёма делается тем же
`leveling.level()`, что и в `build_schedule` (Frappe-обвязка в
`schedule_service.extend_schedule`).

Признак принадлежности плитки программе — `source_program` на самой плитке
(поле `ProdFlow Drum Slot.source_program`): минимально инвазивно, даёт
провенанс «эта плитка из PP-…-00844» и служит ключом идемпотентности.


Портировано из prodflow prodflow/services/drum/extend.py, коммит b1ebde2. Чистое ядро (без frappe) — логика не изменялась, поправлены только импорты.
"""

from __future__ import annotations

from collections.abc import Iterable
from datetime import date


def is_program_covered(existing_source_programs: Iterable[str], program_name: str) -> bool:
	"""Программа уже вложена в график? Ключ идемпотентности продления.

	`existing_source_programs` — множество `source_program` уже существующих
	плиток графика (пустые/None отфильтрованы вызывающим). Повторный вызов
	`extend_schedule` с той же программой не должен задваивать плитки.
	"""
	return program_name in set(existing_source_programs)


def extend_period_to(current_period_to: date, program_to: date) -> date:
	"""Новый конец горизонта графика: максимум из текущего и конца программы.

	Горизонт только растёт: если программа целиком укладывается в уже покрытый
	период (не наш кейс, но перестраховка), конец не сдвигается назад.
	"""
	return max(current_period_to, program_to)
